"""Generate src/platform/factoryActivityTypes.ts from runtime/factorylab/activities.py (TYPES, the one source of truth).

The Cloud Lab › Pipelines editor builds its palette, its required-property checks and its container levels from
this file, so the editor and the runtime's validator agree on what each product supports. Nothing here is
hand-written in TypeScript: change activities.py, then run

    python scripts/authoring/gen_factory_palette.py           # rewrite the TypeScript file
    python scripts/authoring/gen_factory_palette.py --check   # fail when the committed file differs

from the repository root. activities.py has no dependency, so no virtual environment is needed.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "runtime" / "factorylab" / "activities.py"
TARGET = ROOT / "src" / "platform" / "factoryActivityTypes.ts"


def load_activities():
    spec = importlib.util.spec_from_file_location("factorylab_activities", SOURCE)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {SOURCE}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses resolve the module by name
    spec.loader.exec_module(module)
    return module


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def render() -> str:
    activities = load_activities()
    lines = [
        "// Generated by scripts/authoring/gen_factory_palette.py from runtime/factorylab/activities.py. Do not edit:",
        "// change activities.py and run the script (CI runs it with --check).",
        "",
        'import type { FactoryFlavor } from "../webview/contracts";',
        "",
        "export type FactoryActivityCategory = \"control\" | \"move\" | \"transform\" | \"general\" | \"notify\" | \"external\";",
        "",
        "export interface FactoryActivityType {",
        "  /** The JSON `type` of the activity. */",
        "  name: string;",
        "  /** The name the products show in their palette. */",
        "  label: string;",
        "  category: FactoryActivityCategory;",
        "  /** Products that have this activity. */",
        "  flavors: readonly FactoryFlavor[];",
        "  /** Runs inner activities or changes pipeline state (no data work). */",
        "  control: boolean;",
        "  /** typeProperties keys the runtime requires. */",
        "  required: readonly string[];",
        "  /** What to use instead in a product that does not have it. */",
        "  equivalents: Partial<Record<FactoryFlavor, string>>;",
        "}",
        "",
        f"export const FACTORY_FLAVOR_LABELS: Record<FactoryFlavor, string> = {js(activities.FLAVOR_LABELS)};",
        "",
        "export const FACTORY_ACTIVITY_TYPES: readonly FactoryActivityType[] = [",
    ]
    for spec in activities.TYPES.values():
        lines.append(
            "  { "
            f"name: {js(spec.name)}, label: {js(spec.label)}, category: {js(spec.category)}, "
            f"flavors: {js(list(spec.flavors))}, control: {js(spec.control)}, required: {js(list(spec.required))}, "
            f"equivalents: {js(dict(spec.equivalents))} }},"
        )
    lines[-1] = lines[-1].rstrip(",")
    lines += [
        "];",
        "",
        "/** typeProperties keys holding inner activity arrays (a Switch also has cases[].activities). */",
        "export const FACTORY_CONTAINER_KEYS: Record<string, readonly string[]> = "
        + js({key: list(value) for key, value in activities.CONTAINER_KEYS.items()}) + ";",
        "",
        "/** The palette of one product: the activity types its simulator accepts, in the runtime's order. */",
        "export function factoryActivityTypesFor(flavor: FactoryFlavor): FactoryActivityType[] {",
        "  return FACTORY_ACTIVITY_TYPES.filter(type => type.flavors.includes(flavor));",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed file differs")
    args = parser.parse_args()
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if args.check:
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python scripts/authoring/gen_factory_palette.py")
            return 1
        print(f"{TARGET.relative_to(ROOT)} matches runtime/factorylab/activities.py ({text.count('{ name:')} types).")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
