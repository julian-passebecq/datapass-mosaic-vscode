def sections(spec: dict, languages: list[str], source: dict, upstream: list[str]) -> list[dict]:
    tables = "\n".join(f"{name}(" + ", ".join(f"{c} {t}" for c, t in cols.items()) + ")" for name, cols in spec["tables"].items())
    order = spec.get("order_text") or ("Row order is not graded." if not spec.get("ordered") else "")
    output = f"Columns in this order: {', '.join(spec['output'])}. {spec.get('grain', '')} {order}".replace("  ", " ").strip()
    changes = spec.get("changes", [])
    attribution = (f"Adapted from ZillaCode problem {spec['n']}, \"{source['title']}\" ({UPSTREAM}, Apache-2.0), through "
                   "CodeDELeet's normalized import. " + ("Datapass changes: " + " ".join(changes) if changes else
                                                          "Datapass kept the ZillaCode contract; expected rows were recomputed."))
    return [
        {"title": "Tables", "body": tables},
        {"title": "How each engine reads the tables", "body": " ".join(LANGUAGE_NOTES[l] for l in languages)},
        {"title": "Output", "body": output},
        {"title": "Common pitfall", "body": spec["pitfall"]},
        {"title": "Source", "body": attribution},
    ]


def paragraph(text: str) -> str:
    return " ".join(text.split())


