def python_source(spec: dict, body: str, module: str) -> str:
    frame = "pd.DataFrame" if module == "pandas" else "pl.DataFrame"
    header = "import pandas as pd\n" if module == "pandas" else "import polars as pl\n"
    call = ", ".join(f"{frame}({name})" for name in spec["tables"])
    return f"{header}\n{body.strip()}\n\n\ndisplay(etl({call}))\n"


def dbt_source(spec: dict) -> str:
    text = spec["dbt"]
    if text != "auto":
        return text
    text = spec["sql"]
    for name in spec["tables"]:
        text = re.sub(rf"\b(from|join)(\s+){name}\b", rf"\1\2{{{{ source('zilla', '{name}') }}}}", text, flags=re.I)
    return text


def solutions(spec: dict) -> dict[str, str]:
    out = {"sql": spec["sql"], "python": python_source(spec, spec["python"], "pandas"),
           "polars": python_source(spec, spec["polars"], "polars")}
    if spec.get("snowflake"):
        out["snowflake"] = spec["sql"] if spec["snowflake"] == "same" else spec["snowflake"]
    if spec.get("sparklab"):
        out["sparklab"] = spec["sparklab"]
    if spec.get("dbt"):
        out["dbt-sql"] = dbt_source(spec)
    return {language: out[language] for language in LANGUAGES if language in out}


def starters(spec: dict, languages: list[str]) -> dict[str, str]:
    names = list(spec["tables"])
    first = names[0]
    args = ", ".join(names)
    comment = "    # Transform the input DataFrames into the result described in the brief.\n"
    out = {
        "sql": f"-- Return: {', '.join(spec['output'])}\nSELECT *\nFROM {first}\n",
        "snowflake": f"-- Snowflake SQL. Return: {', '.join(spec['output'])}\nSELECT *\nFROM {first}\n",
        "python": python_source(spec, f"def etl({args}):\n{comment}    return {first}", "pandas"),
        "polars": python_source(spec, f"def etl({args}):\n{comment}    return {first}", "polars"),
        "sparklab": "from pyspark.sql import functions as F\nfrom pyspark.sql import Window\n\n"
                    + "".join(f"{n} = spark.table(\"{n}\")\n" for n in names) + f"{first}\n",
        "dbt-sql": f"select *\nfrom {{{{ source('zilla', '{first}') }}}}\n",
    }
    return {language: out[language] for language in languages}


def mutant_sources(spec: dict) -> dict[str, list[str]]:
    out = {}
    for language, items in spec.get("mutants", {}).items():
        if language in ("python", "polars"):
            items = [python_source(spec, body, "pandas" if language == "python" else "polars") for body in items]
        out[language] = items
    return out


