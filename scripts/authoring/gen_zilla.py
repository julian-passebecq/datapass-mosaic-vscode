def convert(value, kind: str):
    if value is None:
        return None
    if kind == "DOUBLE" or kind.startswith("DECIMAL"):
        return float(value)
    if kind in ("INTEGER", "BIGINT"):
        assert float(value) == int(value), value
        return int(value)
    if kind == "BOOLEAN":
        return bool(value)
    return str(value)


def shape(spec: dict, tables: dict[str, list[dict]]) -> dict[str, list[dict]]:
    """Source-named tables -> the contract's tables, columns in declared order, values typed."""
    rename_tables = spec.get("rename_tables", {})
    rename = spec.get("rename", {})
    out = {}
    for source_name, source_rows in tables.items():
        name = rename_tables.get(source_name, source_name)
        declared = spec["tables"][name]
        out_rows = []
        for row in source_rows:
            renamed = {rename.get(k, k): v for k, v in row.items()}
            assert set(renamed) == set(declared), (spec["n"], name, sorted(renamed), list(declared))
            out_rows.append({c: convert(renamed[c], declared[c]) for c in declared})
        out[name] = out_rows
    assert set(out) == set(spec["tables"]), (spec["n"], sorted(out))
    for name, table_rows in out.items():
        assert table_rows, f"zilla {spec['n']}: table {name} is empty (pandas/Polars need at least one row)"
        for column in spec["tables"][name]:
            # Polars infers the Null dtype for an all-NULL column, which no string or number operation accepts.
            assert any(row[column] is not None for row in table_rows), f"zilla {spec['n']}: {name}.{column} is all NULL"
    return out


def literal(value, kind: str) -> str:
    if value is None:
        text = "NULL"
    elif isinstance(value, bool):
        text = "TRUE" if value else "FALSE"
    elif isinstance(value, (int, float)):
        text = repr(value)
    else:
        text = "'" + str(value).replace("'", "''") + "'"
    return f"CAST({text} AS {kind})"


def expected_rows(spec: dict, tables: dict[str, list[dict]]) -> tuple[list[str], list[dict]]:
    """Run the SQL reference on DuckDB over typed tables (the same typing as the grader's CTEs)."""
    from datapass_runtime.catalog import json_value
    con = duckdb.connect()
    try:
        for name, table_rows in tables.items():
            declared = spec["tables"][name]
            selects = [" SELECT " + ", ".join(f"{literal(row[c], t)} AS \"{c}\"" for c, t in declared.items())
                       for row in table_rows]
            con.execute(f'CREATE TABLE "{name}" AS' + " UNION ALL".join(selects))
        cursor = con.execute(spec["sql"])
        columns = [d[0] for d in cursor.description]
        result = [{c: json_value(v) for c, v in zip(columns, row)} for row in cursor.fetchall()]
    finally:
        con.close()
    return columns, result


def fixtures(spec: dict, source: dict) -> list[dict]:
    tests = source["v3"]["tests"]
    items = [("example", "visible", spec.get("visible") or tests[0]["input"], None if spec.get("visible") else tests[0]["expected"])]
    if spec.get("hidden", True) is not False:
        custom = isinstance(spec.get("hidden"), dict)
        items.append(("more-rows", "hidden", spec["hidden"] if custom else tests[1]["input"], None if custom else tests[1]["expected"]))
    for edge in spec.get("edges", []):
        items.append((edge["id"], edge.get("visibility", "edge"), edge["tables"], None))
    out = []
    for check, visibility, raw, zilla_count in items:
        tables = shape(spec, raw)
        columns, result = expected_rows(spec, tables)
        assert columns == spec["output"], (spec["n"], check, columns, spec["output"])
        assert len(result) <= 200
        out.append({"id": check, "visibility": visibility, "input_rows": [], "tables": tables, "expected": result,
                    "_zilla_count": zilla_count})
    return out


def compare_zilla(spec: dict, ours: list[dict], theirs: list[dict]) -> str:
    """Compare recomputed rows with ZillaCode's expected rows (review aid; our contract may differ on purpose)."""
    names = {**{v: k for k, v in spec.get("rename", {}).items()}, **spec.get("zilla_output", {})}
    def key(row: dict, mapping: dict) -> tuple:
        values = []
        for column in spec["output"]:
            value = row.get(mapping.get(column, column), "<missing>")
            values.append(round(float(value), 6) if isinstance(value, (int, float)) and not isinstance(value, bool) else value)
        return tuple(str(v) for v in values)
    mine = sorted(key(r, {}) for r in ours)
    zilla = sorted(key(r, names) for r in theirs)
    if mine == zilla:
        return "same rows"
    missing = [r for r in zilla if r not in mine][:2]
    extra = [r for r in mine if r not in zilla][:2]
    return f"DIFFERS: ZillaCode-only {missing} ours-only {extra}"


