def main() -> None:
    only = None
    if "--only" in sys.argv:
        only = {int(x) for x in sys.argv[sys.argv.index("--only") + 1].split(",")}
    source_pack = json.loads(SOURCE_PACK.read_text(encoding="utf-8"))
    by_number = {int(q["id"].split("-")[1]): q for q in source_pack["questions"]}
    ledger = {p["id"]: p["changes"] for p in json.loads(SOURCE_LEDGER.read_text(encoding="utf-8"))["problems"]}
    specs = load_specs(only)
    scenarios, grading, mutants = [], {}, {}
    for spec in specs:
        source = by_number[spec["n"]]
        fixture_set = fixtures(spec, source)
        counts = {f["id"]: f.pop("_zilla_count") for f in fixture_set}
        public, private = scenario(spec, source, ledger, fixture_set, solutions(spec))
        scenarios.append(public)
        grading[public["semantic"]["id"]] = private
        for language, items in mutant_sources(spec).items():
            assert language in public["variants"], (spec["n"], language)
            mutants[f"{public['semantic']['id']}-{language}"] = items
        print(f"\n=== {public['semantic']['id']} ({', '.join(public['variants'])})")
        for f in fixture_set:
            zilla = counts[f["id"]]
            flag = "" if zilla is None else f" (ZillaCode: {len(zilla)} rows, {compare_zilla(spec, f['expected'], zilla)})"
            print(f"  [{f['visibility']}] {f['id']}: {len(f['expected'])} rows{flag}")
            for row in f["expected"]:
                print("     ", json.dumps(row, ensure_ascii=False))
    manifest = {
        "schema_version": 1, "id": "zilla-v1", "version": "1",
        "title": "ZillaCode problems: one result contract in DuckDB SQL, Snowflake SQL, pandas, Polars, SparkLab and dbt",
        "enabled": True,
        "provenance": {
            "source": f"ZillaCode ({UPSTREAM}), Apache-2.0, through CodeDELeet's normalized import v3-zilla.json",
            "source_sha256": hashlib.sha256(SOURCE_PACK.read_bytes()).hexdigest(),
            "ledger_sha256": hashlib.sha256(SOURCE_LEDGER.read_bytes()).hexdigest(),
            "license": "Apache-2.0 (LICENSE, NOTICE)",
        },
    }
    if only is None:
        PACK.mkdir(parents=True, exist_ok=True)
        (PACK / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        (PACK / "scenarios.json").write_text(json.dumps(scenarios, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        (PACK / "grading.server.json").write_text(json.dumps(grading, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
        (PACK / "LICENSE").write_text(SOURCE_LICENSE.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
        (PACK / "NOTICE").write_text(NOTICE.format(upstream=UPSTREAM, pack_sha=manifest["provenance"]["source_sha256"],
                                                   ledger_sha=manifest["provenance"]["ledger_sha256"]), encoding="utf-8", newline="\n")
        write_mutants(mutants)
    else:
        # Partial runs check the selected problems in a temporary content root and write nothing.
        root = Path(tempfile.mkdtemp(prefix="datapass-zilla-content-"))
        target = root / "exercise-packs" / "zilla-v1"
        target.mkdir(parents=True)
        (target / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8", newline="\n")
        (target / "scenarios.json").write_text(json.dumps(scenarios), encoding="utf-8", newline="\n")
        (target / "grading.server.json").write_text(json.dumps(grading), encoding="utf-8", newline="\n")
        os.environ["DATAPASS_CONTENT_ROOT"] = str(root)
    problems = grade_all(scenarios, mutants)
    print("\nPROBLEMS:\n  " + "\n  ".join(problems) if problems else "\nAll references pass; starters and mutants run and fail.")
    print(f"{len(scenarios)} scenarios, {sum(len(s['variants']) for s in scenarios)} variants, "
          f"{sum(len(m) for m in mutants.values())} mutants.")


if __name__ == "__main__":
    main()
