def grade_all(scenarios: list[dict], mutants: dict[str, list[str]]) -> list[str]:
    from datapass_runtime.execution import Engine
    from datapass_runtime import exercises
    problems: list[str] = []
    with tempfile.TemporaryDirectory(prefix="datapass-zilla-gen-") as folder:
        engine = Engine(Path(folder), "duckdb", trusted_python=True)
        try:
            for item in scenarios:
                for language, variant in item["variants"].items():
                    ident = f"{item['semantic']['id']}-{language}"
                    spec = exercises.definition(ident)

                    def run(code: str) -> dict:
                        return exercises.grade(engine, {
                            "exercise_id": ident, "exercise_version": spec["version"], "language": language,
                            "code": code, "mode": "submit", "notebook_id": "zilla-gen", "cell_id": "solution",
                            "source_revision": 1, "profile": "generic_8x8", "aqe": True})

                    def summary(result: dict) -> str:
                        return "; ".join(f"{c['id']}={c['status']}" + ("" if c["passed"] else f" ({c['message'][:160]})")
                                         for c in result["checks"])

                    reference = run(exercises.solution(ident)["source"])
                    if reference["status"] != "passed":
                        problems.append(f"{ident}: reference {reference['status']}: {summary(reference)}")
                    starter = run(variant["starter_source"])
                    if starter["status"] == "passed":
                        problems.append(f"{ident}: starter passes")
                    elif any(c["execution_status"] != "success" for c in starter["checks"]):
                        problems.append(f"{ident}: starter does not run: {summary(starter)}")
                    for index, mutant in enumerate(mutants.get(ident, [])):
                        graded = run(mutant)
                        if graded["status"] == "passed":
                            problems.append(f"{ident}: mutant #{index} passes")
                        elif any(c["execution_status"] != "success" for c in graded["checks"]):
                            problems.append(f"{ident}: mutant #{index} does not run: {summary(graded)}")
        finally:
            engine.catalog.close()
    return problems


def write_mutants(mutants: dict[str, list[str]]) -> None:
    text = SMOKE.read_text(encoding="utf-8")
    block = MARK_START + "".join(
        f"    {json.dumps(ident)}: [\n" + "".join(f"        {json.dumps(m, ensure_ascii=False)},\n" for m in items) + "    ],\n"
        for ident, items in sorted(mutants.items())) + MARK_END
    if MARK_START in text:
        start = text.index(MARK_START)
        end = text.index(MARK_END) + len(MARK_END)
        text = text[:start] + block + text[end:]
    else:
        anchor = "\n}\n\n\ndef grade("
        assert anchor in text
        text = text.replace(anchor, "\n" + block.rstrip("\n") + "\n}\n\n\ndef grade(", 1)
    SMOKE.write_text(text, encoding="utf-8", newline="\n")


